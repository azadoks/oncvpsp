#!/usr/bin/env python3
"""Writes src/logmesh_weights.inc, the weights of the stencils of logmesh_m.

The weights are rational numbers, computed here exactly (fractions) and
rounded once to double precision: those of the 11-point stencils of d^k/dx^k,
k=0..4, at each node of a window of unit spacing, by Fornberg's algorithm
(Math. Comp. 51, 699 (1988)); and those of the integral over the cell [0,1]
of the degree-7 interpolant through the 8 nodes -ishift..7-ishift, the
integrals of its Lagrange basis polynomials.  They are parameters of
logmesh_m, so the module holds no state.  NHALF and NCELL are those of
logmesh_m.

usage: logmesh_weights.py [OUT]   (OUT defaults to src/logmesh_weights.inc)
       logmesh_weights.py --check FILE
         (exit status 1 if FILE is not what this writes)
"""

import argparse
import sys
from fractions import Fraction
from pathlib import Path

NHALF = 5
NCELL = 8
NDER = 4
WIDTH = 80


def stencil(iz):
    """Weights w[j][k] of node j for d^k/dx^k at node iz (nodes 0..2*NHALF)."""
    nn = 2 * NHALF
    xx = [Fraction(i) for i in range(nn + 1)]
    zz = Fraction(iz)
    ww = [[Fraction(0)] * (NDER + 1) for _ in range(nn + 1)]
    c1 = Fraction(1)
    c4 = xx[0] - zz
    ww[0][0] = Fraction(1)
    for ii in range(1, nn + 1):
        mn = min(ii, NDER)
        c2 = Fraction(1)
        c5 = c4
        c4 = xx[ii] - zz
        for jj in range(ii):
            c3 = xx[ii] - xx[jj]
            c2 *= c3
            if jj == ii - 1:
                for kk in range(mn, 0, -1):
                    ww[ii][kk] = (
                        c1 * (kk * ww[ii - 1][kk - 1] - c5 * ww[ii - 1][kk]) / c2
                    )
                ww[ii][0] = -c1 * c5 * ww[ii - 1][0] / c2
            for kk in range(mn, 0, -1):
                ww[jj][kk] = (c4 * ww[jj][kk] - kk * ww[jj][kk - 1]) / c3
            ww[jj][0] = c4 * ww[jj][0] / c3
        c1 = c2
    return ww


def cell(ishift):
    """Weights of the nodes ii-1-ishift, ii=1..NCELL, for the integral on [0,1]."""
    xx = [Fraction(ii - ishift) for ii in range(NCELL)]
    out = []
    for ii in range(NCELL):
        poly = [Fraction(1)]  # coefficients, lowest first
        den = Fraction(1)
        for jj in range(NCELL):
            if jj == ii:
                continue
            poly = [Fraction(0)] + poly
            for kk in range(len(poly) - 1):
                poly[kk] -= xx[jj] * poly[kk + 1]
            den *= xx[ii] - xx[jj]
        acc = sum(cc / (kk + 1) for kk, cc in enumerate(poly))
        out.append(acc / den)
    return out


def literal(value):
    """The double nearest value, as the shortest Fortran literal that reads back to it."""
    text = repr(float(value))
    if "e" in text:
        mant, expo = text.split("e")
        return f"{mant}d{int(expo)}"
    return f"{text}d0"


def array(name, bounds, values, shape=None):
    """The lines of the parameter array name(bounds) of values, in array
    element order, reshaped to shape if given."""
    items = [literal(vv) for vv in values]
    start = "reshape([" if shape else "["
    end = "],[" + ",".join(shape) + "])" if shape else "]"
    lines = [f" real(dp), parameter :: {name}({bounds})={start} &"]
    line = "&  "
    for ii, item in enumerate(items):
        item += "," if ii < len(items) - 1 else end
        if len(line) + 1 + len(item) + 2 > WIDTH:
            lines.append(line + " &")
            line = "&  "
        line += " " + item
    lines.append(line)
    return lines


def text():
    out = [
        "! Generated by scripts/logmesh_weights.py: do not edit.",
        "! The weights of the stencils of logmesh_m, rational numbers rounded once",
        "! to double precision.",
        "!",
        "! stencil_iz: the weight of node j for d^k/dx^k at node iz of the window",
        "! 0..2*nhalf (unit spacing), for j fastest, then k=0..4",
    ]
    for iz in range(2 * NHALF + 1):
        ww = stencil(iz)
        vals = [ww[jj][kk] for kk in range(NDER + 1) for jj in range(2 * NHALF + 1)]
        out += array(f"stencil_{iz:02d}", "(2*nhalf+1)*5", vals)
    out += [
        "! the stencils of every node",
        " real(dp), parameter :: stencil_table(0:2*nhalf,0:4,0:2*nhalf)=reshape([ &",
    ]
    names = [f"stencil_{iz:02d}" for iz in range(2 * NHALF + 1)]
    out.append("&   " + ",".join(names[:5]) + ", &")
    out.append("&   " + ",".join(names[5:10]) + ", &")
    out.append("&   " + names[10] + "],[2*nhalf+1,5,2*nhalf+1])")
    out += [
        "! cell_table(i,ishift): weight of the node i-1-ishift for the integral",
        "! over the cell [0,1] of the interpolant through the nodes",
        "! -ishift..ncell-1-ishift",
    ]
    vals = [vv for ishift in range(NCELL - 1) for vv in cell(ishift)]
    out += array("cell_table", "ncell,0:ncell-2", vals, ["ncell", "ncell-1"])
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("out", nargs="?", default=None)
    parser.add_argument("--check", metavar="FILE")
    args = parser.parse_args()
    if args.check:
        same = Path(args.check).read_text() == text()
        if not same:
            print(f"{args.check} differs from scripts/logmesh_weights.py's output")
        sys.exit(0 if same else 1)
    out = (
        Path(args.out)
        if args.out
        else Path(__file__).resolve().parent.parent / "src" / "logmesh_weights.inc"
    )
    out.write_text(text())


if __name__ == "__main__":
    main()
